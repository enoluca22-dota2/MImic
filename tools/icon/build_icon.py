"""Build every MImic launcher-icon resource from the SVG masters in design/icon/ (MImic 4.0).

    python tools/icon/build_icon.py <vdt.exe> <render.js>

  vdt.exe    vdtoolkit 0.5 CLI (Apache-2.0, github.com/c5inco/vdtoolkit) — SVG -> VectorDrawable
  render.js  resvg-js wrapper (node render.js in.svg out.png size) — SVG -> PNG

Outputs:
  res/drawable/ic_launcher_{background,foreground,monochrome}.xml   adaptive layers (vector)
  res/mipmap-*/ic_launcher(_round).png                              legacy icons, API 24-25
  docs/icon/mimic_icon_512.png                                      Play Store icon (full square)
  docs/icon/mimic_icon_1024.png, design/icon/mimic_icon_master.svg  brand master + preview
"""
import os
import re
import subprocess
import sys
import tempfile

from PIL import Image, ImageDraw

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ICON = os.path.join(ROOT, "design", "icon")
RES = os.path.join(ROOT, "app", "src", "main", "res")
FOREGROUND = "candidate_a_monogram.svg"
DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
NOTE = "<!-- Generated by tools/icon/build_icon.py from design/icon/*.svg — edit the SVGs, not this file. -->"


def vdt(exe, svg, out):
    subprocess.run([exe, "convert", os.path.join(ICON, svg), "-o", out, "--pretty"], check=True)
    xml = open(out, encoding="utf-8").read()
    if NOTE not in xml:
        xml = re.sub(r"(<vector)", NOTE + "\n\\1", xml, count=1)
        open(out, "w", encoding="utf-8", newline="\n").write(xml)


def render(js, svg, size, tmp):
    out = os.path.join(tmp, f"{os.path.basename(svg)}_{size}.png")
    subprocess.run(["node", js, svg, out, str(size)], check=True)
    return Image.open(out).convert("RGBA")


def composite(js, size, shape, tmp, crop=True):
    """Adaptive-style icon: background + foreground, visible centre 72/108, masked."""
    full = round(size * 108 / 72) * 2 if crop else size * 2
    img = Image.alpha_composite(render(js, os.path.join(ICON, "background.svg"), full, tmp),
                                render(js, os.path.join(ICON, FOREGROUND), full, tmp))
    if crop:
        c = round(full * 18 / 108)
        img = img.crop((c, c, full - c, full - c))
    img = img.resize((size * 2, size * 2), Image.LANCZOS)
    if shape != "square":
        m = Image.new("L", img.size, 0)
        d = ImageDraw.Draw(m)
        inset = img.width * 0.04  # legacy icons keep the platform's small margin
        box = [inset, inset, img.width - inset, img.height - inset]
        if shape == "circle":
            d.ellipse(box, fill=255)
        else:
            d.rounded_rectangle(box, radius=img.width * 0.22, fill=255)
        img.putalpha(m)
    return img.resize((size, size), Image.LANCZOS)


def master_svg():
    """One standalone SVG of the full icon (background + foreground) for brand use."""
    def body(name):
        s = open(os.path.join(ICON, name), encoding="utf-8").read()
        s = re.sub(r"<!--.*?-->", "", s, flags=re.S)
        inner = re.search(r"<svg[^>]*>(.*)</svg>", s, re.S).group(1)
        return inner.replace('id="', f'id="{name[:2]}').replace("url(#", f"url(#{name[:2]}")
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="1080" height="1080">\n'
            "  <!-- MImic icon master (generated from background.svg + the selected foreground). -->\n"
            + body("background.svg") + body(FOREGROUND) + "</svg>\n")


def main():
    exe, js = sys.argv[1], sys.argv[2]
    tmp = tempfile.mkdtemp()
    draw = os.path.join(RES, "drawable")
    vdt(exe, "background.svg", os.path.join(draw, "ic_launcher_background.xml"))
    vdt(exe, FOREGROUND, os.path.join(draw, "ic_launcher_foreground.xml"))
    vdt(exe, "monochrome.svg", os.path.join(draw, "ic_launcher_monochrome.xml"))
    for dens, px in DENSITIES.items():
        folder = os.path.join(RES, f"mipmap-{dens}")
        composite(js, px, "rounded", tmp).save(os.path.join(folder, "ic_launcher.png"), optimize=True)
        composite(js, px, "circle", tmp).save(os.path.join(folder, "ic_launcher_round.png"), optimize=True)
    docs = os.path.join(ROOT, "docs", "icon")
    os.makedirs(docs, exist_ok=True)
    composite(js, 512, "square", tmp).convert("RGB").save(os.path.join(docs, "mimic_icon_512.png"), optimize=True)
    composite(js, 1024, "rounded", tmp).save(os.path.join(docs, "mimic_icon_1024.png"), optimize=True)
    open(os.path.join(ICON, "mimic_icon_master.svg"), "w", encoding="utf-8", newline="\n").write(master_svg())
    print("icon resources written")


if __name__ == "__main__":
    main()
