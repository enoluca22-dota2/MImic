"""MImic launcher icon generator (MImic 3.3).

One geometry spec -> every icon resource, so the vector adaptive icon and the raster fallbacks
always match:

  app/src/main/res/drawable/ic_launcher_background.xml   adaptive background (vector)
  app/src/main/res/drawable/ic_launcher_foreground.xml   adaptive foreground (vector)
  app/src/main/res/drawable/ic_launcher_monochrome.xml   themed-icon layer (Android 13+)
  app/src/main/res/mipmap-*/ic_launcher(_round).png      legacy icons, API 24-25
  docs/icon/mimic_icon_512.png                           Play Store icon
  docs/icon/mimic_icon_1024.png                          preview / source raster

Design: dark navy field with a soft blue/violet glow, a frosted-glass disc, and a beamed
double eighth note in a cyan -> blue -> violet gradient with glass highlights. Everything that
matters sits inside the 66 dp adaptive-icon safe circle (radius 33 around 54,54).

Run from the project root:  python tools/icon/generate_icon.py   (needs Pillow + numpy)
"""
import math
import os

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RES = os.path.join(ROOT, "app", "src", "main", "res")

# ---- geometry (108 x 108 adaptive viewport) ----
NAVY_TOP, NAVY_BOTTOM = "#141B3D", "#05060F"
GLOW = [("#663B82F6", 0.0), ("#337C3AED", 0.55), ("#00000000", 1.0)]  # radial, centre 54,50 r 46
NOTE_STOPS = [("#FF22D3EE", 0.0), ("#FF3B82F6", 0.5), ("#FFA855F7", 1.0)]  # linear 40,30 -> 72,76
NOTE_START, NOTE_END = (40.0, 30.0), (72.0, 76.0)

DISC = (54.0, 54.0, 30.0)                     # glass disc cx, cy, r
HEADS = [(44.0, 68.0), (68.0, 62.0)]          # note-head centres
HEAD_RX, HEAD_RY, HEAD_ROT = 7.6, 5.8, -22.0  # rotated ellipse
STEMS = [(49.6, 64.5, 49.6, 41.0), (73.6, 58.5, 73.6, 35.0)]
STEM_W = 3.4
BEAM_W = 7.0
# Beam: a slanted bar with vertical ends flush with the stems' outer edges.
_BX1, _BX2, _BTOP1, _SLOPE = 49.6 - STEM_W / 2, 73.6 + STEM_W / 2, 38.0, -0.25
BEAM_POLY = [(_BX1, _BTOP1), (_BX2, _BTOP1 + _SLOPE * (_BX2 - _BX1)),
             (_BX2, _BTOP1 + _SLOPE * (_BX2 - _BX1) + BEAM_W), (_BX1, _BTOP1 + BEAM_W)]
BEAM = (_BX1 + 1.5, _BTOP1 + 3.5, _BX2 - 1.5, _BTOP1 + 3.5 + _SLOPE * (_BX2 - _BX1 - 3))  # centre line


def ellipse_path(cx, cy, rx, ry):
    return (f"M{cx - rx:.2f},{cy:.2f}a{rx:.2f},{ry:.2f} 0,1 0,{2 * rx:.2f},0"
            f"a{rx:.2f},{ry:.2f} 0,1 0,{-2 * rx:.2f},0Z")


def circle_path(cx, cy, r):
    return ellipse_path(cx, cy, r, r)


def gradient_xml(kind, stops, **attrs):
    a = " ".join(f'android:{k}="{v}"' for k, v in attrs.items())
    items = "\n".join(f'                <item android:color="{c}" android:offset="{o}" />' for c, o in stops)
    return (f'            <gradient android:type="{kind}" {a}>\n{items}\n            </gradient>')


def note_fill(attr="fillColor"):
    return (f'        <aapt:attr name="android:{attr}">\n'
            + gradient_xml("linear", NOTE_STOPS, startX=NOTE_START[0], startY=NOTE_START[1],
                           endX=NOTE_END[0], endY=NOTE_END[1])
            + "\n        </aapt:attr>")


HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n'
          '<!-- Generated by tools/icon/generate_icon.py — edit the script, not this file. -->\n'
          '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
          '    xmlns:aapt="http://schemas.android.com/aapt"\n'
          '    android:width="108dp" android:height="108dp"\n'
          '    android:viewportWidth="108" android:viewportHeight="108">\n')


def note_paths(solid=None):
    """The note: round-capped stems, a slanted beam bar, heads as rotated ellipses."""
    out = []
    for x1, y1, x2, y2 in STEMS:
        stroke = f'android:strokeColor="{solid}"' if solid else ""
        body = "" if solid else "\n" + note_fill("strokeColor")
        out.append(f'    <path android:pathData="M{x1},{y1}L{x2},{y2}" android:strokeWidth="{STEM_W}"\n'
                   f'        android:strokeLineCap="round" {stroke}>{body}\n    </path>')
    poly = "M" + "L".join(f"{x:.2f},{y:.2f}" for x, y in BEAM_POLY) + "Z"
    fill = f'android:fillColor="{solid}"' if solid else ""
    body = "" if solid else "\n" + note_fill()
    out.append(f'    <path android:pathData="{poly}" {fill}>{body}\n    </path>')
    for cx, cy in HEADS:
        fill = f'android:fillColor="{solid}"' if solid else ""
        body = "" if solid else "\n" + note_fill()
        out.append(f'    <group android:pivotX="{cx}" android:pivotY="{cy}" android:rotation="{HEAD_ROT}">\n'
                   f'    <path android:pathData="{ellipse_path(cx, cy, HEAD_RX, HEAD_RY)}" {fill}>{body}\n    </path>\n'
                   f'    </group>')
    return "\n".join(out)


def background_xml():
    return (HEADER
            + '    <path android:pathData="M0,0h108v108h-108z">\n'
            + '        <aapt:attr name="android:fillColor">\n'
            + gradient_xml("linear", [(f"#FF{NAVY_TOP[1:]}", 0.0), (f"#FF{NAVY_BOTTOM[1:]}", 1.0)],
                           startX=30, startY=0, endX=78, endY=108)
            + '\n        </aapt:attr>\n    </path>\n'
            + '    <path android:pathData="M0,0h108v108h-108z">\n'
            + '        <aapt:attr name="android:fillColor">\n'
            + gradient_xml("radial", GLOW, centerX=54, centerY=50, gradientRadius=46)
            + '\n        </aapt:attr>\n    </path>\n</vector>\n')


def foreground_xml():
    cx, cy, r = DISC
    sheen = f"M{cx - r + 3:.1f},{cy - 2:.1f}A{r - 3},{r - 3} 0,0 1,{cx + r - 3:.1f},{cy - 2:.1f}A{r * 1.6:.1f},{r * 1.2:.1f} 0,0 0,{cx - r + 3:.1f},{cy - 2:.1f}Z"
    parts = [HEADER.rstrip("\n")]
    # soft glow behind the note
    parts.append('    <path android:pathData="' + circle_path(60, 52, 26) + '">\n'
                 '        <aapt:attr name="android:fillColor">\n'
                 + gradient_xml("radial", [("#3322D3EE", 0.0), ("#337C3AED", 0.5), ("#00000000", 1.0)],
                                centerX=60, centerY=52, gradientRadius=26)
                 + '\n        </aapt:attr>\n    </path>')
    # frosted glass disc + rim + top sheen
    parts.append(f'    <path android:pathData="{circle_path(cx, cy, r)}" android:fillColor="#14FFFFFF"\n'
                 f'        android:strokeColor="#2EFFFFFF" android:strokeWidth="0.8" />')
    parts.append(f'    <path android:pathData="{sheen}">\n'
                 '        <aapt:attr name="android:fillColor">\n'
                 + gradient_xml("linear", [("#33FFFFFF", 0.0), ("#00FFFFFF", 1.0)],
                                startX=cx, startY=cy - r, endX=cx, endY=cy)
                 + '\n        </aapt:attr>\n    </path>')
    parts.append(note_paths())
    # glass highlights on the heads and the beam
    for hx, hy in HEADS:
        parts.append(f'    <group android:pivotX="{hx}" android:pivotY="{hy}" android:rotation="{HEAD_ROT}">\n'
                     f'    <path android:pathData="{ellipse_path(hx - 2.2, hy - 2.4, 3.2, 1.3)}" android:fillColor="#73FFFFFF" />\n'
                     f'    </group>')
    x1, y1, x2, y2 = BEAM
    parts.append(f'    <path android:pathData="M{x1 + 0.5:.1f},{y1 - 1.9:.1f}L{x2 - 0.5:.1f},{y2 - 1.9:.1f}" android:strokeWidth="1.3"\n'
                 f'        android:strokeLineCap="round" android:strokeColor="#66FFFFFF" />')
    return "\n".join(parts) + "\n</vector>\n"


def monochrome_xml():
    return HEADER + note_paths(solid="#FF000000") + "\n</vector>\n"


# ---- raster rendering (same spec, supersampled) ----

def hex_rgba(h):
    h = h.lstrip("#")
    if len(h) == 6:
        h = "FF" + h
    a, r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4, 6))
    return np.array([r, g, b, a], dtype=np.float64)


def ramp(t, stops):
    t = np.clip(t, 0, 1)
    cols = [hex_rgba(c) for c, _ in stops]
    offs = [o for _, o in stops]
    out = np.zeros(t.shape + (4,))
    for i in range(4):
        out[..., i] = np.interp(t, offs, [c[i] for c in cols])
    return out


def linear(size, s, p0, p1, stops):
    yy, xx = np.mgrid[0:size, 0:size] / s
    dx, dy = p1[0] - p0[0], p1[1] - p0[1]
    t = ((xx - p0[0]) * dx + (yy - p0[1]) * dy) / (dx * dx + dy * dy)
    return ramp(t, stops)


def radial(size, s, c, r, stops):
    yy, xx = np.mgrid[0:size, 0:size] / s
    return ramp(np.hypot(xx - c[0], yy - c[1]) / r, stops)


def over(dst, src, mask=None):
    """Premultiplied 'source over' of an RGBA float image, optionally through a 0..1 mask."""
    a = src[..., 3:4] / 255.0
    if mask is not None:
        a = a * mask[..., None]
    da = dst[..., 3:4] / 255.0
    out_a = a + da * (1 - a)
    rgb = (src[..., :3] * a + dst[..., :3] * da * (1 - a)) / np.maximum(out_a, 1e-6)
    return np.concatenate([rgb, out_a * 255.0], axis=-1)


def mask_of(size, draw_fn):
    m = Image.new("L", (size, size), 0)
    draw_fn(ImageDraw.Draw(m))
    return np.asarray(m, dtype=np.float64) / 255.0


def rotated_ellipse(d, s, cx, cy, rx, ry, rot):
    pts = []
    for i in range(96):
        a = 2 * math.pi * i / 96
        x, y = rx * math.cos(a), ry * math.sin(a)
        c, sn = math.cos(math.radians(rot)), math.sin(math.radians(rot))
        pts.append(((cx + x * c - y * sn) * s, (cy + x * sn + y * c) * s))
    d.polygon(pts, fill=255)


def capped_line(d, s, x1, y1, x2, y2, w):
    d.line([(x1 * s, y1 * s), (x2 * s, y2 * s)], fill=255, width=max(1, round(w * s)))
    r = w * s / 2
    for x, y in ((x1, y1), (x2, y2)):
        d.ellipse([x * s - r, y * s - r, x * s + r, y * s + r], fill=255)


def note_mask(size, s):
    def draw(d):
        for st in STEMS:
            capped_line(d, s, *st, STEM_W)
        d.polygon([(x * s, y * s) for x, y in BEAM_POLY], fill=255)
        for cx, cy in HEADS:
            rotated_ellipse(d, s, cx, cy, HEAD_RX, HEAD_RY, HEAD_ROT)
    return mask_of(size, draw)


def render_layers(size):
    """Full 108-unit adaptive canvas at [size] px: (background, foreground) float RGBA."""
    s = size / 108.0
    bg = linear(size, s, (30, 0), (78, 108), [(NAVY_TOP, 0), (NAVY_BOTTOM, 1)])
    bg = over(bg, radial(size, s, (54, 50), 46, GLOW))

    fg = np.zeros((size, size, 4))
    fg = over(fg, radial(size, s, (60, 52), 26, [("#3322D3EE", 0), ("#337C3AED", 0.5), ("#00000000", 1)]))
    cx, cy, r = DISC
    disc = mask_of(size, lambda d: d.ellipse([(cx - r) * s, (cy - r) * s, (cx + r) * s, (cy + r) * s], fill=255))
    fg = over(fg, np.broadcast_to(hex_rgba("#14FFFFFF"), fg.shape).copy(), disc)
    rim = mask_of(size, lambda d: d.ellipse([(cx - r) * s, (cy - r) * s, (cx + r) * s, (cy + r) * s],
                                            outline=255, width=max(1, round(0.8 * s))))
    fg = over(fg, np.broadcast_to(hex_rgba("#2EFFFFFF"), fg.shape).copy(), rim)
    # sheen: upper part of the disc, fading downwards (approximation of the vector crescent)
    yy = np.mgrid[0:size, 0:size][0] / s
    upper = disc * np.clip((cy - 2 - yy) / (r - 2), 0, 1) ** 0.6
    fg = over(fg, np.broadcast_to(hex_rgba("#33FFFFFF"), fg.shape).copy(), upper * 0.8)

    note = note_mask(size, s)
    grad = linear(size, s, NOTE_START, NOTE_END, NOTE_STOPS)
    # outer glow: blurred note in the same gradient
    glow = np.asarray(Image.fromarray((note * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(3.0 * s)), dtype=np.float64) / 255.0
    fg = over(fg, grad, glow * 0.55)
    fg = over(fg, grad, note)

    def hl(d):
        for hx, hy in HEADS:
            rotated_ellipse(d, s, hx - 2.2, hy - 2.4, 3.2, 1.3, HEAD_ROT)
    fg = over(fg, np.broadcast_to(hex_rgba("#73FFFFFF"), fg.shape).copy(), mask_of(size, hl))
    x1, y1, x2, y2 = BEAM
    beam_hl = mask_of(size, lambda d: capped_line(d, s, x1 + 0.5, y1 - 1.9, x2 - 0.5, y2 - 1.9, 1.3))
    fg = over(fg, np.broadcast_to(hex_rgba("#66FFFFFF"), fg.shape).copy(), beam_hl)
    return bg, fg


def composite(size, shape):
    """Launcher-style icon: the visible 72-of-108 area, masked to [shape] ('square', 'rounded', 'circle')."""
    ss = max(1, min(4, 2048 // size))  # supersampling, capped to keep memory reasonable
    big = int(round(size * 108 / 72)) * ss
    bg, fg = render_layers(big)
    img = over(bg, fg)
    crop = int(round(big * 18 / 108))
    img = img[crop:big - crop, crop:big - crop]
    pil = Image.fromarray(np.clip(img, 0, 255).astype(np.uint8), "RGBA").resize((size * 4, size * 4), Image.LANCZOS)  # noqa
    if shape != "square":
        m = Image.new("L", pil.size, 0)
        d = ImageDraw.Draw(m)
        inset = size * 4 * 0.04  # legacy icons keep a small margin like the platform's own
        box = [inset, inset, size * 4 - inset, size * 4 - inset]
        if shape == "circle":
            d.ellipse(box, fill=255)
        else:
            d.rounded_rectangle(box, radius=size * 4 * 0.22, fill=255)
        pil.putalpha(Image.fromarray(np.minimum(np.asarray(pil)[..., 3], np.asarray(m))))
    return pil.resize((size, size), Image.LANCZOS)


DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def main():
    def write(path, text):
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)

    write(os.path.join(RES, "drawable", "ic_launcher_background.xml"), background_xml())
    write(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), foreground_xml())
    write(os.path.join(RES, "drawable", "ic_launcher_monochrome.xml"), monochrome_xml())
    for dens, px in DENSITIES.items():
        folder = os.path.join(RES, f"mipmap-{dens}")
        for old in ("ic_launcher.webp", "ic_launcher_round.webp"):
            p = os.path.join(folder, old)
            if os.path.exists(p):
                os.remove(p)
        composite(px, "rounded").save(os.path.join(folder, "ic_launcher.png"), optimize=True)
        composite(px, "circle").save(os.path.join(folder, "ic_launcher_round.png"), optimize=True)
    out = os.path.join(ROOT, "docs", "icon")
    os.makedirs(out, exist_ok=True)
    composite(512, "square").convert("RGB").save(os.path.join(out, "mimic_icon_512.png"), optimize=True)
    composite(1024, "rounded").save(os.path.join(out, "mimic_icon_1024.png"), optimize=True)
    print("icon resources written")


if __name__ == "__main__":
    main()
